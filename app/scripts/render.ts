// Export render with Remotion: bundles src/composition (the same code as the preview) and renders the EDL.
// Media are read over HTTP from the backend, so nothing is copied out of the video folder.
//
// Usage: tsx scripts/render.ts --video <dir> --edl <edl.json> --theme <theme.json>
//          --video-base <url> --library-base <url> --out <file.mp4> [--frames a-b] [--still <frame> --still-out <png>]
import {existsSync, readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {basename, join, resolve} from 'node:path';
import {bundle} from '@remotion/bundler';
import {renderMedia, renderStill, selectComposition} from '@remotion/renderer';
import type {Edl} from '../src/edl/types';
import {ThemeSchema, resolveTheme} from '../src/model/theme';

const args = new Map<string, string>();
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i += 2) args.set(argv[i].replace(/^--/, ''), argv[i + 1]);
const need = (key: string): string => {
	const v = args.get(key);
	if (!v) throw new Error(`missing --${key}`);
	return v;
};

const appDir = resolve(import.meta.dirname, '..');
const videoDir = resolve(need('video'));
const edl: Edl = JSON.parse(readFileSync(need('edl'), 'utf-8'));
// The video's own theme overrides (text styles edited in the Styles tab...) apply at export like in the preview.
const planFile = join(videoDir, 'data/plan.json');
const overrides = existsSync(planFile) ? JSON.parse(readFileSync(planFile, 'utf-8')).themeOverrides : undefined;
const theme = resolveTheme(ThemeSchema.parse(JSON.parse(readFileSync(need('theme'), 'utf-8'))), overrides);
const progress = (fraction: number, message: string) => console.log(`PROGRESS ${fraction.toFixed(3)} ${message}`);

// Escape hatch diagrams: import only the hand-written components the EDL uses.
const writeRegistry = () => {
	const used = new Set(edl.diagrams.filter((d) => d.template === 'custom' && d.component).map((d) => d.component!));
	const schemasDir = join(videoDir, 'diagrams');
	const files = existsSync(schemasDir) ? readdirSync(schemasDir).filter((f) => f.endsWith('.tsx')) : [];
	const lines = ['// Generated by scripts/render.ts before each export bundle. Do not edit.'];
	const entries: string[] = [];
	for (const component of used) {
		const file = files.find((f) => basename(f, '.tsx') === component);
		if (!file) throw new Error(`custom diagram ${component} not found in ${schemasDir}`);
		const source = readFileSync(join(schemasDir, file), 'utf-8');
		const exported = /export const (\w+)\s*:/.exec(source)?.[1];
		if (!exported) throw new Error(`no exported component in ${file}`);
		const alias = `C_${entries.length}`;
		lines.push(`import {${exported} as ${alias}} from ${JSON.stringify(join(schemasDir, file).replace(/\\/g, '/'))};`);
		entries.push(`${JSON.stringify(component)}: ${alias}`);
	}
	lines.push(`export const customDiagrams: Record<string, any> = {${entries.join(', ')}};`);
	writeFileSync(join(appDir, 'src/composition/custom/registry.generated.ts'), lines.join('\n') + '\n');
};

const EMPTY_REGISTRY = '// Generated by scripts/render.ts before each export bundle. Do not edit.\nexport const customDiagrams = {};\n';

const main = async () => {
	writeRegistry();
	try {
		await renderAll();
	} finally {
		// The generated imports point into a video folder: never leave them for the typecheck or the next bundle.
		writeFileSync(join(appDir, 'src/composition/custom/registry.generated.ts'), EMPTY_REGISTRY);
	}
};

const renderAll = async () => {
	progress(0.02, 'bundling');
	const kit = join(appDir, 'src/composition/kit');
	const serveUrl = await bundle({
		entryPoint: join(appDir, 'src/composition/index.ts'),
		onProgress: (p) => progress(0.02 + (p / 100) * 0.08, 'bundling'),
		webpackOverride: (config) => ({
			...config,
			resolve: {
				...config.resolve,
				alias: {
					...(config.resolve?.alias ?? {}),
					'@kit/schema': join(kit, 'schema.tsx'),
					'@kit/types': join(kit, 'types.ts'),
					'@kit/theme': join(kit, 'theme.ts'),
				},
				// Hand-written diagrams live in projects/, outside app/, and still need its React, Remotion and rough.js.
				modules: [join(appDir, 'node_modules'), 'node_modules'],
			},
		}),
	});

	const audio = JSON.parse(readFileSync(join(videoDir, 'data/render/audio.json'), 'utf-8'));
	const subscribe = existsSync(join(videoDir, 'data/cache/subscribe.webm')) ? 'data/cache/subscribe.webm' : null;
	const inputProps = {
		edl,
		theme,
		media: {videoBase: need('video-base'), libraryBase: need('library-base')},
		audio: {mode: 'export', voice: audio.voice, music: audio.music, sfxGains: audio.sfxGains},
		subscribeFile: subscribe,
		mattes: existsSync(join(videoDir, 'data/cache/matte/index.json'))
			? JSON.parse(readFileSync(join(videoDir, 'data/cache/matte/index.json'), 'utf-8'))
			: [],
	};
	const composition = await selectComposition({serveUrl, id: 'Main', inputProps});

	// Stills: --stills 30,120,300 --still-dir <dir> (frame numbers), used for visual checks.
	const stills = args.get('stills');
	if (stills) {
		for (const f of stills.split(',').map(Number)) {
			const output = join(need('still-dir'), `still_${String(f).padStart(5, '0')}.png`);
			await renderStill({composition, serveUrl, inputProps, frame: f, output, imageFormat: 'png'});
			console.log('still ->', output);
		}
		return;
	}

	const frames = args.get('frames');
	const frameRange = frames ? (frames.split('-').map(Number) as [number, number]) : null;
	await renderMedia({
		composition,
		serveUrl,
		inputProps,
		codec: 'h264',
		crf: theme.format.crf,
		x264Preset: theme.format.preset as 'veryfast',
		pixelFormat: 'yuv420p',
		// BT.709 limited range, tagged, like the rush and what the platforms expect. Remotion's v4 default wrote an
		// untagged full range BT.601 file (yuvj420p): players and platforms re-encoding it shifted the colours.
		// PNG frames keep the colour conversion exact (Remotion's recommendation with an explicit colour space).
		colorSpace: 'bt709',
		imageFormat: 'png',
		audioBitrate: theme.format.audioBitrate as `${number}k`,
		outputLocation: need('out'),
		frameRange,
		overwrite: true,
		onProgress: ({progress: p, renderedFrames, encodedFrames}) => {
			progress(0.1 + p * 0.9, `render ${renderedFrames}/${composition.durationInFrames} (encoded ${encodedFrames})`);
		},
	});
	console.log('render ->', need('out'));
};

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
