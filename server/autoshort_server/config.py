"""App configuration: config.json at the repo root, overridden by config.local.json (not committed)."""
import json
import os
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SERVER = REPO / "server"
APP = REPO / "app"
SCHEMA_DIR = REPO / "schema"
THEME_FILE = REPO / "theme" / "theme.json"
APP_DIR_NAME = "data"  # generated by the app in each project: projects/<slug>/data/
EXPORTS_DIR_NAME = "exports"  # rendered videos, never overwritten: projects/<slug>/exports/
DIAGRAMS_DIR_NAME = "diagrams"  # optional hand-written diagrams: projects/<slug>/diagrams/*.tsx


@dataclass(frozen=True)
class Config:
    projects_root: Path
    library_root: Path
    ai_python: Path
    claude_command: str
    backend_port: int
    frontend_port: int

    @property
    def app_python(self) -> Path:
        return venv_python(SERVER / ".venv")


def venv_python(venv: Path) -> Path:
    """The interpreter of a virtual environment: Scripts/python.exe on Windows, bin/python elsewhere."""
    return venv / "Scripts" / "python.exe" if os.name == "nt" else venv / "bin" / "python"


def _path(value: str) -> Path:
    """Paths in config.json are relative to the app folder unless absolute."""
    path = Path(value)
    return path if path.is_absolute() else REPO / path


def _python(value: str) -> Path:
    """aiPython: a virtual environment folder (portable) or an interpreter path."""
    path = _path(value)
    return path if path.suffix == ".exe" or path.name.startswith("python") else venv_python(path)


@lru_cache
def load_config() -> Config:
    data = json.loads((REPO / "config.json").read_text(encoding="utf-8"))
    local = REPO / "config.local.json"
    if local.exists():
        data.update(json.loads(local.read_text(encoding="utf-8")))
    return Config(
        projects_root=_path(data["projectsRoot"]),
        library_root=_path(data["libraryRoot"]),
        ai_python=_python(data["aiPython"]),
        claude_command=data.get("claudeCommand", "claude"),
        backend_port=int(data.get("backendPort", 8765)),
        frontend_port=int(data.get("frontendPort", 5173)),
    )
